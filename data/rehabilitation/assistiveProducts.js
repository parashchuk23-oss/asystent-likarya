export function getVerifiedAssistiveProducts(routeId, domainIds) {
  return verifiedAssistiveProductMappings.filter(
    (mapping) => mapping.routeId === routeId && mapping.domainIds.some((domainId) => domainIds.includes(domainId)),
  );
}

export function getVerifiedAssistiveProductsByIcdCode(icdCode) {
  const normalizedCode = String(icdCode || '').trim().toUpperCase().replace(/\s+/g, '');
  if (!normalizedCode) return [];
  return verifiedAssistiveProductMappings.filter((mapping) => mapping.icdCodes.some((code) => (
    normalizedCode === code || normalizedCode.startsWith(`${code}.`)
  )));
}

export function getAssistiveProductReadiness(product, confirmations = {}) {
  const statuses = product.criteria.map((criterion) => confirmations[`${product.id}:${criterion.id}`] || 'unassessed');
  return {
    ready: statuses.length > 0 && statuses.every((status) => status === 'confirmed'),
    confirmedCount: statuses.filter((status) => status === 'confirmed').length,
    missingCount: statuses.filter((status) => status === 'unassessed').length,
    rejectedCount: statuses.filter((status) => status === 'not-confirmed').length,
  };
}
